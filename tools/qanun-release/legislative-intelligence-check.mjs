import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {policyPdf,policyHash} from './legislative-intelligence.mjs';
const output=process.argv[2];
if(!output)throw Error('Provide public output directory');
const read=name=>fs.readFileSync(path.join(output,name),'utf8');
const page=read('legislative-intelligence.html');
assert.equal((page.match(/<main /g)||[]).length,1);
assert.equal((page.match(/<figure /g)||[]).length,2);
for(const text of ['Evolutionary','Strategic','Anticipatory','Co-central','competent institutions','62 pages','Read policy paper online','download="Legislative_Intelligence_Policy_Paper_FINAL.pdf"'])assert.ok(page.includes(text),text);
for(const file of ['index.html','legislation.html','case-law.html','rule-workbench.html','laws/pk-code-6c462b7d924dbbe3.html'])assert.ok(read(file).includes('href="/legislative-intelligence"'),file);
assert.match(read('index.html'),/id="li-home-title">Legislative Intelligence/);
const bytes=fs.readFileSync(path.join(output,policyPdf));
assert.equal(bytes.subarray(0,5).toString(),'%PDF-');
assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),policyHash);
assert.ok(fs.statSync(path.join(output,'publications/legislative-intelligence-cover.png')).size>10000);
console.log('POLICY_PUBLICATION_PASS: two infographics, source-identical PDF, reading and download links, shared navigation');
