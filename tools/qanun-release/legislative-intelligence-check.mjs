import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {policyPdf,policyHash,policyCollection} from './legislative-intelligence.mjs';
const output=process.argv[2];
if(!output)throw Error('Provide public output directory');
const read=name=>fs.readFileSync(path.join(output,name),'utf8');
const page=read('legislative-intelligence.html');
assert.equal((page.match(/<main /g)||[]).length,1);
assert.equal((page.match(/<figure /g)||[]).length,2);
for(const text of ['Evolutionary','Strategic','Anticipatory','Co-central','competent institutions','Publication status and access',policyCollection])assert.ok(page.includes(text),text);
for(const file of ['index.html','legislation.html','case-law.html','rule-workbench.html','laws/pk-code-6c462b7d924dbbe3.html'])assert.ok(read(file).includes('href="/legislative-intelligence"'),file);
assert.match(read('index.html'),/id="li-home-title">Legislative Intelligence/);
assert.equal(fs.existsSync(path.join(output,policyPdf)),false,'Withdrawn local PDF was republished');
const redirects=JSON.parse(fs.readFileSync(new URL('../../vercel.json',import.meta.url),'utf8')).redirects;assert.ok(redirects.some(r=>r.source===policyPdf&&r.destination===policyCollection),'Existing publication redirect missing');
const bytes=fs.readFileSync(new URL('./publications/Legislative_Intelligence_Policy_Paper_FINAL.pdf',import.meta.url));
assert.equal(bytes.subarray(0,5).toString(),'%PDF-');
assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),policyHash);
assert.ok(fs.statSync(path.join(output,'publications/legislative-intelligence-cover.png')).size>10000);
console.log('POLICY_PUBLICATION_PASS: two infographics, existing publication-collection access, no local withdrawn PDF, shared navigation');
